#!/usr/bin/env node
// Scans the source for every class string that makes a pill (rounded-full), groups identical ones, and writes the result for the
// components showcase at /dev/components. Run it again after changing styles:  node scripts/style-inventory.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../src", import.meta.url).pathname;
const skip = (path) => /\/(app\/dev|components\/dev)\//.test(path);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.tsx?$/.test(name) && !/\.test\./.test(name) && !skip(path)) files.push(path);
  }
})(root);

let helperUses = 0;
const literal = /(["'`])((?:\\.|(?!\1)[^\\])*?)\1/gs;
const found = new Map();
for (const file of files) {
  const text = readFileSync(file, "utf8");
  helperUses += (text.match(/\bbtn\.(primary|secondary|quiet|danger)\b/g) || []).length;
  for (const m of text.matchAll(literal)) {
    let value = m[2].replace(/\$\{[^}]*\}/g, " ").replace(/\s+/g, " ").trim();
    if (!value.includes("rounded-full") || value.length > 320 || !/^[\w\s\-:/\[\]().,%#!@&'>*]+$/.test(value) || /[.]{2}|\bfunction\b/.test(value)) continue;
    const entry = found.get(value) ?? { classes: value, count: 0, files: new Set() };
    entry.count++;
    entry.files.add(relative(root, file));
    found.set(value, entry);
  }
}

const part = (re, s) => (s.match(re) || [])[0] ?? null;
const kindOf = (c) => {
  if (/placeholder:|focus:border-ink/.test(c) && /bg-surface/.test(c)) return "field";
  if (/bg-danger(?!\/)/.test(c) && /font-bold/.test(c)) return "danger solid";
  if (/bg-accent/.test(c) && /font-bold/.test(c) && /min-h-/.test(c)) return "primary";
  if (/border-danger-line|text-danger/.test(c) && /min-h-/.test(c)) return "danger outline";
  if (/border-ink/.test(c) && /(min-h-|px-)/.test(c)) return "secondary";
  if (/(^| )pill( |$)/.test(c) || (/border-line/.test(c) && /min-h-/.test(c))) return "secondary muted";
  if (/(^| )text-muted( |$)/.test(c) && /hover:/.test(c)) return "quiet";
  if (/py-(0\.5|1|1\.5)( |$)/.test(c) && /text-(xs|\[13px\]|sm)/.test(c) || /px-(2|2\.5|3)( |$)/.test(c) && /py-/.test(c)) return "tag or chip";
  return "other";
};

const rows = [...found.values()]
  .map((e) => ({
    classes: e.classes,
    count: e.count,
    files: [...e.files].sort(),
    kind: kindOf(e.classes),
    height: part(/min-h-\[?[\w.:()@\-\]]+/, e.classes),
    padding: part(/(?<![\w-])px-[\w.]+/, e.classes),
    text: part(/text-(xs|sm|base|lg|\[\d+px\])/, e.classes),
  }))
  .sort((a, b) => a.kind.localeCompare(b.kind) || b.count - a.count);

writeFileSync(
  new URL("../src/app/dev/components/inventory.generated.ts", import.meta.url),
  `// Generated by scripts/style-inventory.mjs. Do not edit by hand.\nexport interface Variant { classes: string; count: number; files: string[]; kind: string; height: string | null; padding: string | null; text: string | null }\nexport const HELPER_USES = ${helperUses};\nexport const VARIANTS: Variant[] = ${JSON.stringify(rows, null, 1)};\n`,
);
const byKind = {};
for (const r of rows) {
  byKind[r.kind] ??= { variants: 0, uses: 0, heights: new Set(), paddings: new Set(), texts: new Set() };
  const k = byKind[r.kind];
  k.variants++; k.uses += r.count; if (r.height) k.heights.add(r.height); if (r.padding) k.paddings.add(r.padding); if (r.text) k.texts.add(r.text);
}
for (const [kind, k] of Object.entries(byKind)) console.log(kind.padEnd(16), `${String(k.variants).padStart(3)} variants, ${String(k.uses).padStart(3)} uses | heights ${k.heights.size}, paddings ${k.paddings.size}, text sizes ${k.texts.size}`);
console.log("total", rows.length, "variants from", files.length, "files");
