#!/usr/bin/env node
// Reads the colour tokens from globals.css (dark and light), counts how often each is used in the source, and lists every colour
// written by hand instead of through a token. Output feeds the palette page at /dev/palette. Run again after changing colours:
//   node scripts/palette-inventory.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../src", import.meta.url).pathname;
const css = readFileSync(join(root, "app/globals.css"), "utf8");

const block = (start) => {
  const i = css.indexOf(start);
  if (i < 0) return {};
  const body = css.slice(css.indexOf("{", i) + 1, css.indexOf("}", i));
  return Object.fromEntries([...body.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
};
const dark = block(":root {");
const light = { ...dark, ...block(':root[data-theme="light"]') };
delete dark["color-scheme"];
delete light["color-scheme"];

const names = Object.keys(dark).filter((n) => !["color-scheme"].includes(n));
const classOf = { bg: "bg", surface: "surface", "surface-2": "surface-2", text: "ink", muted: "muted", line: "line", accent: "accent", "accent-text": "accent-text", "on-accent": "on-accent", "add-bg": "add-bg", "add-line": "add-line", "add-text": "add-text", danger: "danger", "danger-line": "danger-line" };

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(tsx?|css)$/.test(name) && !/\.test\./.test(name) && !/\/(app\/dev|components\/dev)\//.test(path) && !path.endsWith("inventory.generated.ts")) files.push(path);
  }
})(root);

const uses = Object.fromEntries(names.map((n) => [n, { classes: 0, vars: 0 }]));
const raw = new Map();
const rawRe = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g;
for (const file of files) {
  const text = readFileSync(file, "utf8");
  const isTokens = file.endsWith("globals.css");
  for (const n of names) {
    const c = classOf[n];
    if (c) uses[n].classes += (text.match(new RegExp(`(?<![\\w-])(?:text|bg|border|ring|outline|divide|from|to|via|fill|stroke|shadow|decoration|caret|accent)-${c}(?![\\w-])`, "g")) || []).length;
    uses[n].vars += (text.match(new RegExp(`var\\(--${n}\\)`, "g")) || []).length;
  }
  if (isTokens) continue;
  for (const m of text.matchAll(rawRe)) {
    const v = m[0].replace(/\s+/g, " ").toLowerCase();
    const e = raw.get(v) ?? { value: v, count: 0, files: new Set() };
    e.count++;
    e.files.add(relative(root, file));
    raw.set(v, e);
  }
}

const rows = names.map((n) => ({ name: n, dark: dark[n], light: light[n], classUses: uses[n].classes, varUses: uses[n].vars }));
const rawRows = [...raw.values()].map((e) => ({ value: e.value, count: e.count, files: [...e.files].sort() })).sort((a, b) => b.count - a.count);
writeFileSync(
  new URL("../src/app/dev/palette/palette.generated.ts", import.meta.url),
  `// Generated by scripts/palette-inventory.mjs. Do not edit by hand.\nexport const TOKENS = ${JSON.stringify(rows, null, 1)};\nexport const RAW = ${JSON.stringify(rawRows, null, 1)};\n`,
);
console.log(`${rows.length} tokens, ${rawRows.length} hand-written colours in ${rawRows.reduce((s, r) => s + r.count, 0)} places, from ${files.length} files`);
for (const r of rows) console.log(r.name.padEnd(13), `${String(r.classUses).padStart(4)} class uses, ${String(r.varUses).padStart(3)} var() uses`);
